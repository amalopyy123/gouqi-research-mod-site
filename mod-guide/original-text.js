  function applySection(id, entries) {
    const section = document.querySelector(`#${id}`);
    const cards = Array.from(document.querySelectorAll(`#${id} .feature-card`));
    while (cards.length < entries.length && cards.length > 0) {
      const clone = cards[cards.length - 1].cloneNode(true);
      cards[cards.length - 1].after(clone);
      cards.push(clone);
    }
    entries.forEach((entry, index) => {
      const card = cards[index];
      if (!card) return;
      const title = card.querySelector("h3");
      if (title) title.textContent = entry[0];
      card.querySelectorAll(":scope > p").forEach((paragraph) => paragraph.remove());
      const gallery = card.querySelector(":scope > .gallery");
      entry[1].forEach((text) => {
        const paragraph = document.createElement("p");
        paragraph.textContent = text;
        card.insertBefore(paragraph, gallery || null);
      });
    });
  }

